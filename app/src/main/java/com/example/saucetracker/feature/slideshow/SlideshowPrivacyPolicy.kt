internal object SlideshowPrivacyPolicy {
    fun shouldObfuscate(enabled: Boolean): Boolean =
        GitHubMediaSession.shouldApplyPrivacyMask(enabled)
}
internal fun Modifier.slideshowPrivacyObfuscate(
    enabled: Boolean,
    overlayColor: Color,
    blurRadius: Dp = 7.dp,
    expandHorizontal: Dp = 2.dp,
    expandVertical: Dp = 1.dp,
    cornerRadius: Dp = 12.dp
): Modifier {
    if (!SlideshowPrivacyPolicy.shouldObfuscate(enabled)) return this
    val shape = RoundedCornerShape(cornerRadius)
    return this
        .padding(horizontal = expandHorizontal, vertical = expandVertical)
        .clip(shape)
        .blur(blurRadius, edgeTreatment = BlurredEdgeTreatment.Unbounded)
        .drawWithContent {
            drawContent()
            val radius = cornerRadius.toPx()
            drawRoundRect(
                color = overlayColor,
                cornerRadius = CornerRadius(radius, radius)
            )
            drawRoundRect(
                color = overlayColor.copy(alpha = (overlayColor.alpha + 0.16f).coerceAtMost(1f)),
                cornerRadius = CornerRadius(radius, radius),
                style = Stroke(width = 1.dp.toPx())
            )
        }
        .clip(shape)
}
